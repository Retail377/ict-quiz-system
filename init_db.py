    print("=" * 60)

    db = Database()

    # 检查是否已有题目
    existing_count = db.get_total_question_count()
    if existing_count > 0:
        print(f"⚠️ 数据库中已有 {existing_count} 道题目")
        choice = input("是否继续导入示例题目？(y/n): ").strip().lower()
        if choice != 'y':
            print("已取消导入")
            return

    print(f"\n📥 正在导入 {len(SAMPLE_QUESTIONS)} 道示例题目...")

    count = db.batch_add_questions(SAMPLE_QUESTIONS)

    print(f"\n✅ 成功导入 {count} 道题目")

    # 显示分类统计
    categories = db.get_categories()
    print("\n📊 各考点题目数量:")
    for cat in categories:
        print(f"  {cat['category']}: {cat['count']} 题")

    print("\n" + "=" * 60)
    print("🎉 数据库初始化完成！")
    print("=" * 60)
    print("\n下一步:")
    print("  1. 启动Web应用: python app.py")
